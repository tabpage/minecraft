export const ITEM_REGISTRY: Map<number, ItemDefinition> = new Map(
  REGISTRY_LIST.map((def) => [def.id, def])
);

export const ALL_ITEMS: ItemDefinition[] = REGISTRY_LIST.filter(
  (def) =>
    def.id !== BLOCK.AIR &&
    def.id !== BLOCK.WATER &&
    def.id !== BLOCK.FARMLAND &&
    def.id !== BLOCK.FARMLAND_WET &&
    def.id !== BLOCK.WHEAT_1 &&
    def.id !== BLOCK.WHEAT_2 &&
    def.id !== BLOCK.WHEAT_3 &&
    def.id !== BLOCK.SPARK_WIRE &&
    def.id !== BLOCK.SPARK_WIRE_ON &&
    def.id !== BLOCK.SPARK_LAMP_ON
);

export function getItemDef(id: number): ItemDefinition {
  return ITEM_REGISTRY.get(id) ?? ITEM_REGISTRY.get(BLOCK.AIR)!;
}

export function isBlockSolid(blockId: number): boolean {
  const def = ITEM_REGISTRY.get(blockId);
  return Boolean(def?.solid);
}

export function isBlockTransparent(blockId: number): boolean {
  if (blockId === BLOCK.AIR) return true;
  const def = ITEM_REGISTRY.get(blockId);
  return Boolean(def?.transparent);
}

export function isBlockLiquid(blockId: number): boolean {
  const def = ITEM_REGISTRY.get(blockId);
  return Boolean(def?.liquid);
}

export function isLogBlock(blockId: number): boolean {
  return blockId === BLOCK.OAK_LOG || blockId === BLOCK.BIRCH_LOG || blockId === BLOCK.PINE_LOG;
}

export function createItemStack(itemId: number, count = 1): ItemStack {
  const def = getItemDef(itemId);
  const stack: ItemStack = {
    itemId,
    count: Math.min(count, def.stackSize),
  };
  if (def.maxDurability) {
    stack.durability = def.maxDurability;
    stack.maxDurability = def.maxDurability;
  }
  return stack;
}

export function getEnchantLevel(stack: ItemStack | null | undefined, type: string): number {
  if (!stack?.enchantments) return 0;
  const found = stack.enchantments.find((e) => e.type === type);
  return found ? found.level : 0;
}

export function computeMiningTime(blockId: number, held: ItemStack | null): number {
  const bDef = getItemDef(blockId);
  if (bDef.hardness === undefined || bDef.hardness < 0) return Infinity;
  if (bDef.hardness === 0) return 0.05;

  let speed = 1.0;
  const toolDef = held ? getItemDef(held.itemId) : null;
  const isRightTool =
    toolDef && bDef.preferredTool && toolDef.toolType === bDef.preferredTool;

  if (isRightTool && toolDef?.miningSpeed) {
    speed = toolDef.miningSpeed;
    const eff = getEnchantLevel(held, 'efficiency');
    if (eff > 0) speed += eff * 1.8;
  } else if (bDef.minToolTier && bDef.minToolTier > 0) {
    // Mining stone/ores by hand is much slower
    speed = 0.35;
  }

  return Math.max(0.08, bDef.hardness / speed);
}

export function canHarvestBlock(blockId: number, held: ItemStack | null): boolean {
  const bDef = getItemDef(blockId);
  if (!bDef.minToolTier || bDef.minToolTier <= 0) return true;
  if (!held) return false;
  const toolDef = getItemDef(held.itemId);
  if (!toolDef.toolType || toolDef.toolType !== bDef.preferredTool) return false;
  return (toolDef.toolTier ?? 0) >= bDef.minToolTier;
}

export function computeAttackDamage(held: ItemStack | null): number {
  if (!held) return 2;
  const def = getItemDef(held.itemId);
  const base = def.attackDamage ?? 2;
  const sharp = getEnchantLevel(held, 'sharpness');
  return base + sharp * 2;
}
